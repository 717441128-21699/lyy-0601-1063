export const getJobById = (id: string): Job | undefined => {
  return jobs.find(j => j.id === id);
};

export const getJobsByCompanyId = (companyId: string): Job[] => {
  return jobs.filter(j => j.companyId === companyId && j.status === 'active');
};

export const getActiveJobs = (): Job[] => {
  return jobs.filter(j => j.status === 'active');
};

export const getPendingJobs = (): Job[] => {
  return jobs.filter(j => j.status === 'pending');
};

export const getSimilarJobs = (jobId: string, limit = 4): Job[] => {
  const currentJob = jobs.find(j => j.id === jobId);
  if (!currentJob) return [];
  
  return jobs
    .filter(j => j.id !== jobId && j.status === 'active')
    .filter(j => {
      const tagMatch = j.tags.filter(t => currentJob.tags.includes(t)).length;
      const cityMatch = j.location.city === currentJob.location.city;
      return tagMatch > 0 || cityMatch;
    })
    .sort((a, b) => {
      const aMatch = a.tags.filter(t => currentJob.tags.includes(t)).length;
      const bMatch = b.tags.filter(t => currentJob.tags.includes(t)).length;
      return bMatch - aMatch;
    })
    .slice(0, limit);
};
